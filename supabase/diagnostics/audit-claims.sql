 'bucket',(select jsonb_build_object('id',id,'public',public,'limit',file_size_limit,'mime',allowed_mime_types) from storage.buckets where id='claim-evidence'),
 'realtime',(select coalesce(jsonb_agg(tablename),'[]'::jsonb) from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename in(select name from expected_tables)),
