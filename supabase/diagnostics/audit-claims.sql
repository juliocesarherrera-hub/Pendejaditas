 'columns',(select coalesce(jsonb_agg(jsonb_build_object('table',table_name,'column',column_name,'type',data_type,'nullable',is_nullable,'default',column_default)),'[]'::jsonb) from information_schema.columns where table_schema='public' and table_name in(select name from expected_tables)),
 'indexes',(select coalesce(jsonb_agg(to_jsonb(i)),'[]'::jsonb) from pg_indexes i where i.schemaname='public' and i.tablename in(select name from expected_tables))
)) as claims_audit;
